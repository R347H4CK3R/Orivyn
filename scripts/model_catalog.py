#!/usr/bin/env python3
"""Validate reviewed publisher/template evidence and deterministically emit Swift."""
import argparse, json, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'docs/model-catalog/catalog.json'
OUTPUT = ROOT / 'JarvisEVO/Providers/Local/LocalModelCatalogData.swift'

def quote(value):
    escapes = {'"': '\\"', '\\': '\\\\', '\n': '\\n', '\r': '\\r', '\t': '\\t'}
    return '"' + ''.join((escapes.get(c, '\\u{' + format(ord(c), 'x') + '}' if ord(c) < 32 else c) for c in value)) + '"'

def validate(document, evidence, templates):
    models = document.get('models', [])
    if not models:
        raise ValueError('Empty catalog')
    sources = {s['repository']: s for s in evidence.get('sources', [])}
    probes = {(p['repository'], p['file']): p for p in templates}
    ids = set()
    names = set()
    for model in models:

        def require(condition, message):
            if not condition:
                raise ValueError(model.get('id', 'unknown') + ': ' + message)
        for key in ['id', 'name', 'baseModel', 'family', 'purpose', 'quantization', 'notes']:
            require(isinstance(model.get(key), str) and model[key].strip(), 'Missing ' + key)
        require(re.fullmatch('[a-z0-9._-]+', model['id']), 'Unsafe ID')
        require(model['id'] not in ids, 'Duplicate ID')
        ids.add(model['id'])
        require(re.fullmatch('(Qwen|HuggingFaceTB)/[A-Za-z0-9._-]+', model.get('repository', '')) or model.get('repository') == 'ggml-org/Qwen3-1.7B-GGUF', 'Unreviewed publisher')
        require(re.fullmatch('[a-f0-9]{40}', model.get('revision', '')), 'Pin an immutable revision')
        require(re.fullmatch('[A-Za-z0-9._-]+\\.gguf', model.get('fileName', '')), 'Unsafe filename')
        require(model['fileName'].lower() not in names, 'Duplicate filename')
        names.add(model['fileName'].lower())
        require(type(model.get('byteCount')) is int and 24 <= model['byteCount'] <= 2000000000, 'File size exceeds limit')
        require(re.fullmatch('[a-f0-9]{64}', model.get('sha256', '')), 'Invalid hash')
        require(model.get('license') == 'Apache-2.0' and model.get('publisherLicense') == 'apache-2.0', 'Unreviewed license')
        require(model.get('gated') is False, 'Gated models excluded')
        require(re.fullmatch('[A-Za-z0-9._-]+', model.get('licensePath', '')), 'Unsafe license path')
        require(re.fullmatch('[a-f0-9]{64}', model.get('licenseSHA256', '')), 'Invalid license digest')
        require(type(model.get('recommendedRAMGB')) is int and 3 <= model['recommendedRAMGB'] <= 16, 'Invalid RAM guidance')
        require(model['purpose'] in ['General chat', 'Coding', 'Reasoning'], 'Unknown purpose')
        require(model.get('architecture') in ['qwen2', 'qwen3', 'llama'], 'Unsupported architecture')
        source = sources.get(model['repository'], {})
        require(source.get('revision') == model['revision'], 'Revision conflicts with reviewed evidence')
        require(source.get('licenseSHA256') == model['licenseSHA256'], 'License digest conflicts with reviewed evidence')
        require(source.get('licenseURL') == 'https://huggingface.co/' + model['repository'] + '/resolve/' + model['revision'] + '/' + model['licensePath'], 'License URL conflicts with reviewed evidence')
        require(source.get('publisherLicense') == model['publisherLicense'] and source.get('gated') is False, 'Publisher terms conflict with evidence')
        artifact = next((f for f in source.get('files', []) if f['fileName'] == model['fileName']), {})
        require(artifact.get('sha256') == model['sha256'] and artifact.get('byteCount') == model['byteCount'], 'Artifact conflicts with publisher evidence')
        probe = probes.get((model['repository'], model['fileName']), {})
        require(probe.get('revision') == model['revision'] and probe.get('architecture') == model['architecture'], 'Exact-file template evidence missing or mismatched')
        require(type(probe.get('renderedBytes')) is int and probe['renderedBytes'] > 0 and re.fullmatch('[a-f0-9]{64}', probe.get('templateSHA256', '')), 'Template probe failed')
    if document.get('defaultModelID') not in ids:
        raise ValueError('Missing default model')
    return models

def render(document, evidence, templates):
    models = validate(document, evidence, templates)
    lines = ['// Reconstructed catalog. Generated by scripts/model_catalog.py; do not hand edit.', 'import Foundation', '', 'extension LocalModelCatalog {', '    static let entries: [LocalModelCatalogEntry] = [']
    for m in models:
        base = 'https://huggingface.co/' + m['repository']
        revision = m['revision']
        lines += ['        LocalModelCatalogEntry(', '            descriptor: LocalModelDescriptor(']
        for key in ['id', 'name', 'fileName']:
            lines.append('                ' + key + ': ' + quote(m[key]) + ',')
        lines += ['                downloadURL: URL(string: ' + quote(base + '/resolve/' + revision + '/' + m['fileName']) + '),', '                sha256: ' + quote(m['sha256']) + ',', '                byteCount: ' + str(m['byteCount']) + ',', '                license: ' + quote(m['license']) + ',', '                sourceURL: URL(string: ' + quote(base + '/tree/' + revision) + ')', '            ),']
        for key in ['baseModel', 'family', 'purpose', 'quantization']:
            lines.append('            ' + key + ': ' + quote(m[key]) + ',')
        lines += ['            recommendedRAMGB: ' + str(m['recommendedRAMGB']) + ',', '            notes: ' + quote(m['notes']) + ',', '            licenseURL: URL(string: ' + quote(base + '/blob/' + revision + '/' + m['licensePath']) + ')', '        ),']
    lines += ['    ]', '    static let defaultModelID = ' + quote(document['defaultModelID']), '}', '']
    return '\n'.join(lines)

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--catalog', type=pathlib.Path, default=CATALOG)
    p.add_argument('--evidence', type=pathlib.Path, default=CATALOG.parent / 'publisher-evidence.json')
    p.add_argument('--templates', type=pathlib.Path, default=CATALOG.parent / 'template-evidence.json')
    p.add_argument('--output', type=pathlib.Path, default=OUTPUT)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    try:
        data = render(json.loads(a.catalog.read_text()), json.loads(a.evidence.read_text()), json.loads(a.templates.read_text()))
        if a.check:
            if not a.output.exists() or a.output.read_text() != data:
                raise ValueError('Generated catalog missing or stale')
        else:
            a.output.write_text(data)
    except (OSError, ValueError, KeyError) as e:
        print(str(e), file=sys.stderr)
        return 1
    return 0
if __name__ == '__main__':
    sys.exit(main())
