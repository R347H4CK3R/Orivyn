import SwiftUI

/// Explicitly user-operated deterministic tool, not an AI model response.
struct CalculatorView: View {
    @State private var expression: String
    @State private var result: String?
    @State private var error: String?

    init(request: String = "") {
        let range = request.range(of: #"(?i)^\s*(?:please\s+)?calculate\s+"#, options: .regularExpression)
        _expression = State(initialValue: range.map { String(request[$0.upperBound...]) } ?? "")
    }

    var body: some View {
        Form {
            Section("Expression") {
                TextField("For example: (12 + 8) / 4", text: $expression, axis: .vertical)
                    .textInputAutocapitalization(.never).autocorrectionDisabled()
                    .keyboardType(.asciiCapable)
                    .accessibilityIdentifier("calculator.expression")
                    .onChange(of: expression) { _, _ in result = nil; error = nil }
                Button("Calculate", action: calculate)
                    .disabled(expression.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty)
                    .accessibilityIdentifier("calculator.calculate")
            }
            if let result {
                Section("Result") {
                    Text(result).font(.title2.monospaced()).textSelection(.enabled)
                        .accessibilityIdentifier("calculator.result")
                    Text("Calculated on this iPhone, not generated by an AI model.")
                        .font(.caption).foregroundStyle(.secondary)
                }
            }
            if let error { Section { Text(error).foregroundStyle(.red).accessibilityIdentifier("calculator.error") } }
            Section("Supported operations") {
                Text("Add, subtract, multiply, divide, parentheses and decimal numbers. No functions, exponents, percentages or code execution.")
                Text("Uses approximate floating-point arithmetic, not exact financial or scientific computation. Inputs are limited to 256 UTF-8 bytes. Nothing is sent over the network.")
                    .font(.caption).foregroundStyle(.secondary)
            }
        }.navigationTitle("Calculator")
    }

    private func calculate() {
        do {
            let value = try LocalCalculator.evaluate(expression)
            result = String(format: "%.15g", locale: Locale(identifier: "en_US_POSIX"), value == 0 ? 0 : value)
            error = nil
        } catch {
            result = nil
            self.error = error.localizedDescription
        }
    }
}
